@Composable
fun HomeMorphIcon(
    selected: Boolean,
    modifier: Modifier = Modifier,
    size: Dp = 24.dp,
    tint: Color = LocalContentColor.current,
    contentDescription: String? = "Home",
) {
    val animatable = remember { Animatable(0f) }

    LaunchedEffect(selected) {
        if (selected) {
            animatable.snapTo(0f)
            animatable.animateTo(
                targetValue = 1f,
                animationSpec = tween(
                    durationMillis = 1167,
                    easing = LinearEasing
                )
            )
        } else {
            animatable.snapTo(0f)
        }
    }

    val descModifier = if (contentDescription != null) {
        modifier.semantics { this.contentDescription = contentDescription }
    } else {
        modifier
    }

    val bodyPath = remember { Path() }
    val doorPath = remember { Path() }

    val progress = animatable.value
    val frameFloat = (progress * 27f).coerceIn(0f, 27f)
    val lowerIndex = frameFloat.toInt().coerceIn(0, 26)
    val upperIndex = lowerIndex + 1
    val frac = frameFloat - lowerIndex

    Canvas(modifier = descModifier.size(size)) {
        buildInterpolatedPath(bodyPath, HOME_BODY_FRAMES, 10, lowerIndex, upperIndex, frac)
        buildInterpolatedPath(doorPath, HOME_DOOR_FRAMES, 6, lowerIndex, upperIndex, frac)

        val scale = this.size.minDimension / 24f
        val centerX = this.size.width / 2f
        val centerY = this.size.height / 2f

        translate(left = centerX, top = centerY - 0.284f * scale) {
            scale(scaleX = scale, scaleY = scale, pivot = Offset.Zero) {
                drawPath(path = bodyPath, color = tint.copy(alpha = tint.alpha * 0.35f))
                drawPath(path = doorPath, color = tint)
            }
        }
    }
}

private fun lerp(start: Float, stop: Float, fraction: Float): Float =
    start + (stop - start) * fraction

private fun buildInterpolatedPath(
    path: Path,
    frames: FloatArray,
    numSegments: Int,
    lowerIndex: Int,
    upperIndex: Int,
    frac: Float,
) {
    path.rewind()
    val floatsPerFrame = 2 + numSegments * 6
    val lowerOffset = lowerIndex * floatsPerFrame
    val upperOffset = upperIndex * floatsPerFrame

    val startX = lerp(frames[lowerOffset], frames[upperOffset], frac)
    val startY = lerp(frames[lowerOffset + 1], frames[upperOffset + 1], frac)
    path.moveTo(startX, startY)

    var offset = 2
    for (i in 0 until numSegments) {
        val cp1x = lerp(frames[lowerOffset + offset], frames[upperOffset + offset], frac)
        val cp1y = lerp(frames[lowerOffset + offset + 1], frames[upperOffset + offset + 1], frac)
        val cp2x = lerp(frames[lowerOffset + offset + 2], frames[upperOffset + offset + 2], frac)
        val cp2y = lerp(frames[lowerOffset + offset + 3], frames[upperOffset + offset + 3], frac)
        val endX = lerp(frames[lowerOffset + offset + 4], frames[upperOffset + offset + 4], frac)
        val endY = lerp(frames[lowerOffset + offset + 5], frames[upperOffset + offset + 5], frac)
        path.cubicTo(cp1x, cp1y, cp2x, cp2y, endX, endY)
        offset += 6
    }
    path.close()
}

